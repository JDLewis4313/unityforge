def get_verse_for_date(date_obj) -> str:
    """
    Get verse based on date object.
    Returns consistent verse for the same date.
    """
    day_of_year = date_obj.timetuple().tm_yday
    # Handle leap years - if day 366, use last verse
    if day_of_year > 365:
        day_of_year = 365
    
    return DAILY_VERSES[day_of_year - 1]  # Convert to 0-based index

def get_themed_verse(theme: str, seed: int = None) -> str:
    """
    Get a verse from a specific theme.
    If seed provided, uses it for consistent selection.
    """
    import random
    
    if theme not in THEMED_VERSES:
        return "John 3:16"
    
    verses = THEMED_VERSES[theme]
    if seed is not None:
        random.seed(seed)
    
    return random.choice(verses)

def get_random_daily_verse(day_of_year: int) -> str:
    """
    Get a specific verse for each day of the year (1-365).
    """
    if 1 <= day_of_year <= 365:
        return DAILY_VERSES[day_of_year - 1]
    return "John 3:16"  # Fallback